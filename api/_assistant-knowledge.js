'use strict';

const Model = require('../js/backend/model.js');

function plansText() {
  const lines = [];
  Object.keys(Model.PLANS).forEach(function (id) {
    const plan = Model.PLANS[id];
    const range = plan.maxEmployees
      ? plan.minEmployees + ' עד ' + plan.maxEmployees + ' עובדים'
      : plan.minEmployees + ' עובדים ומעלה';
    lines.push('- ' + id + ': ' + range + ' — ' +
      (plan.quote ? 'לפי הצעת מחיר' : plan.priceMonthly + ' ₪ לחודש'));
  });
  return lines.join('\n');
}

